def validate_waveforms():
    for name, segments in WAVEFORM_V3.items():
        if not 1 <= len(segments) <= 100:
            raise ValueError(f"Invalid waveform length: {name}")
        for segment in segments:
            if not re.fullmatch(r"[0-9A-F]{16}", segment):
                raise ValueError(f"Invalid waveform HEX: {name}")
            values = bytes.fromhex(segment)
            if any(v > 240 for v in values[:4]) or any(v > 100 for v in values[4:]):
                raise ValueError(f"Invalid waveform bytes: {name}")
        # Check both actual Python sender and backend-to-APP envelopes, including IDs.
        payload = "pulse-A:" + json.dumps(segments, separators=(",", ":"))
        for kind in (4, "msg"):
            envelope = dict(type=kind, clientId="0"*36, targetId="0"*36, message=payload)
            if len(json.dumps(envelope)) > 1950:
                raise ValueError(f"Waveform message too long: {name}")


validate_waveforms()

